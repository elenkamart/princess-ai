// Rebuilds lib/features/dressup/dressup_art_data.dart from art.js.
// Usage (from the mobile folder): node tool/dressup_art/generate.js
'use strict';
const fs = require('fs');
const path = require('path');
const A = require('./art.js');

const out = path.join(__dirname, '..', '..', 'lib', 'features', 'dressup', 'dressup_art_data.dart');
const SKIN = '__SKIN__', HAIR = '__HAIR__';
const s = (v) => JSON.stringify(v).replace(/\$/g, '\\$');
const map = (obj) => '{\n' + Object.entries(obj).map(([k, v]) => `  ${s(k)}: ${s(v)},`).join('\n') + '\n}';

const ids = new Set();
for (const it of A.ITEMS) {
  if (ids.has(it.id)) throw new Error('duplicate item ' + it.id);
  ids.add(it.id);
  for (const f of it.fits) if (!A.OCCASIONS[f]) throw new Error(it.id + ' fits unknown occasion ' + f);
}

const P = (style, mood) => A.parts(SKIN, HAIR, style, mood);
const hairBack = Object.fromEntries(A.LOOKS.style.map((st) => [st, P(st, 'ok').hairBack]));
const faces = Object.fromEntries(['ok', 'happy', 'oops'].map((m) => [m, P('puffs', m).face]));
const base = P('puffs', 'ok');

const items = A.ITEMS.map((it) => {
  const o = { color: it.color, skin: SKIN };
  return `  DressUpItem(id: ${s(it.id)}, name: ${s(it.name)}, slot: ${s(it.slot)}, fits: ${s(it.fits)}, tags: ${s(it.tags)}, plural: ${!!it.plural},\n` +
    `      viewBox: ${s(A.THUMBS[it.id] || A.THUMBS[it.slot])},\n      back: ${s(it.back ? it.back(o) : '')},\n      front: ${s(it.draw(o))}),`;
}).join('\n');

const occ = Object.entries(A.OCCASIONS).map(([id, o]) =>
  `  ${s(id)}: DressUpOccasionText(name: ${s(o.name)}, outdoor: ${o.outdoor}, hello: ${s(o.hello)}, yay: ${s(o.yay)}),`).join('\n');

const dart = `// GENERATED by tool/dressup_art/generate.js from tool/dressup_art/art.js.
// Edit the art there and run \`node tool/dressup_art/generate.js\` from the mobile folder.

class DressUpItem {
  const DressUpItem({
    required this.id,
    required this.name,
    required this.slot,
    required this.fits,
    required this.tags,
    required this.plural,
    required this.viewBox,
    required this.back,
    required this.front,
  });

  final String id;
  final String name;
  final String slot;

  /// Occasions the piece suits.
  final List<String> fits;

  /// Weather the piece is made for: rain, warm (cold and snow) or cool (hot days).
  final List<String> tags;
  final bool plural;

  /// Crop of the 240 x 400 character space used for the closet thumbnail.
  final String viewBox;

  /// SVG drawn behind the body (backpacks) and over it. May contain [kSkinToken].
  final String back;
  final String front;
}

class DressUpOccasionText {
  const DressUpOccasionText({required this.name, required this.outdoor, required this.hello, required this.yay});

  final String name;

  /// Whether the day's weather matters for this occasion.
  final bool outdoor;
  final String hello;
  final String yay;
}

const String kSkinToken = ${s(SKIN)};
const String kHairToken = ${s(HAIR)};
const String kInk = ${s(A.INK)};

const List<String> kSkins = ${s(A.LOOKS.skin)};
const List<String> kHairColors = ${s(A.LOOKS.hair)};
const List<String> kHairStyles = ${s(A.LOOKS.style)};

const Map<String, String> kHairBack = ${map(hairBack)};
const String kBodyLower = ${s(base.bodyLower)};
const String kUndershirt = ${s(base.undershirt)};
const String kUndershorts = ${s(base.undershorts)};
const String kBodyUpper = ${s(base.bodyUpper)};
const Map<String, String> kFaces = ${map(faces)};
const String kHairFront = ${s(base.hairFront)};

const List<String> kSlots = ${s(A.SLOTS.map((x) => x[0]))};
const Map<String, String> kSlotNames = ${map(Object.fromEntries(A.SLOTS))};

const List<DressUpItem> kItems = [
${items}
];

const Map<String, DressUpOccasionText> kOccasions = {
${occ}
};

/// 24 x 24 stroke icons (draw with stroke = currentColor).
const Map<String, String> kIconPaths = ${map(A.ICON_PATHS)};

/// Occasion scenes in a 400 x 440 space; Lulu goes at translate(80 34).
const Map<String, String> kBackdrops = ${map(A.BACKDROPS)};

/// Weather drawn over outdoor scenes: nice, rain, snow, cold, hot.
const Map<String, String> kWeatherOverlays = ${map(A.WEATHER_OVERLAYS)};
`;
fs.writeFileSync(out, dart);
console.log('wrote', path.relative(process.cwd(), out), '-', A.ITEMS.length, 'items,', Object.keys(A.OCCASIONS).length, 'occasions');
